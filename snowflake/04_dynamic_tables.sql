SELECT
  e.ID AS ENTITY_ID,
  e.NAME AS ENTITY_NAME,
  e.REGION,
  e.CATEGORY,
  e.STATUS,
  COUNT(*) AS EVENT_COUNT,
  SUM(CASE WHEN f.KPI_FABRIC_ON_TIME <= (SELECT T FROM thresh) THEN 1 ELSE 0 END) AS ALERT_COUNT,
  ROUND(AVG(f.KPI_FABRIC_ON_TIME), 2) AS AVG_FABRIC_ON_TIME,
  ROUND(AVG(f.KPI_LEAD_TIME_AVG), 2) AS AVG_LEAD_TIME,
  ROUND(AVG(f.KPI_INVENTORY_DAYS), 2) AS AVG_INVENTORY_DAYS,
  ROUND(AVG(f.KPI_FABRIC_UTILIZATION), 2) AS AVG_FABRIC_UTILIZATION,
  ROUND(AVG(f.KPI_TRIM_AVAILABILITY), 2) AS AVG_TRIM_AVAILABILITY,
  ROUND(AVG(f.KPI_IMPORT_DEPENDENCY), 2) AS AVG_IMPORT_DEPENDENCY
FROM RAW.FABRIC_SHIPMENTS f
JOIN RAW.SUPPLIERS e ON e.ID = f.ENTITY_ID
